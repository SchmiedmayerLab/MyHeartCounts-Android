"""Project the Grove FHIR catalogs onto the Kotlin canonical contract.

The Swift and TypeScript contracts have always been generated from the catalogs; this one was
hand-written, so it could fall behind without anything failing. Generating it closes the last
place where a catalog change reaches two languages and silently misses the third.
"""

